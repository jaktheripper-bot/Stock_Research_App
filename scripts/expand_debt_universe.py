def main():
    root = Path(__file__).resolve().parent.parent
    debt_universe_path = root / "core" / "db" / "debt_universe.py"

    # Load existing module
    import importlib.util
    spec = importlib.util.spec_from_file_location("core.db.debt_universe", debt_universe_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    existing_universe = list(module.CANONICAL_DEBT_UNIVERSE)

    existing_isins = {s["isin"].upper() for s in existing_universe}
    print(f"Existing count: {len(existing_universe)}")

    to_add = [s for s in ADDITIONAL_INSTRUMENTS if s["isin"].upper() not in existing_isins]
    print(f"Adding {len(to_add)} new instruments...")

    full_universe = existing_universe + to_add
    print(f"Total universe size: {len(full_universe)}")

    assert len(full_universe) >= 105, f"Expected at least 105, got {len(full_universe)}"

    # Format into python code
    import json
    code = '"""Canonical Benchmark Universe for Indian Corporate Debt, NCDs, and SDIs.\n\n'
    code += 'Complies with SEBI (Issue and Listing of Non-Convertible Securities) Regulations\n'
    code += 'and the SEBI ₹10,000 Face Value Democratization Framework (July 2024 Amendments).\n\n'
    code += f'Contains {len(full_universe)} benchmark corporate debt instruments spanning 5 essential institutional segments:\n'
    code += '1. PSU & Sovereign-Backed Quasi-Gilt Bonds (25 instruments: PFC, REC, NTPC, NHAI, IRFC, IOCL, etc.)\n'
    code += '2. Marquee Conglomerates & Corporate Giants (25 instruments: RIL, Tata Motors, L&T, TCS, M&M, etc.)\n'
    code += '3. Premier Banking & Financial Institutions (Senior, Tier-II & Infra) (25 instruments: SBI, HDFC, ICICI, etc.)\n'
    code += '4. Infrastructure, Energy & Green Concession Bonds (15 instruments: Adani Ports, ReNew, Avaada, etc.)\n'
    code += '5. Securitised Debt Instruments (SDIs) & Retail ₹10,000 NCDs (15 instruments: InvoiceX, LoanX, LeaseX, etc.)\n\n'
    code += 'Guarantees 100% offline availability on cold boot, during testing, and under restricted network environments.\n'
    code += '"""\n\n'
    code += 'from typing import List, Dict, Any\n\n'
    code += 'CANONICAL_DEBT_UNIVERSE: List[Dict[str, Any]] = [\n'

    for i, s in enumerate(full_universe):
        code += '    {\n'
        code += f'        "isin": "{s["isin"]}",\n'
        code += f'        "ticker": "{s.get("ticker", "")}",\n'
        code += f'        "scrip_code": "{s.get("scrip_code", "")}",\n'
        code += f'        "series": "{s.get("series", "N1")}",\n'
        code += f'        "instrument_name": "{s["instrument_name"]}",\n'
        code += f'        "instrument_type": "{s["instrument_type"]}",\n'
        code += f'        "seniority_tier": "{s["seniority_tier"]}",\n'
        code += f'        "face_value": {float(s["face_value"])},\n'
        code += f'        "coupon_rate_pct": {float(s["coupon_rate_pct"])},\n'
        code += f'        "coupon_frequency": "{s["coupon_frequency"]}",\n'
        code += f'        "issue_date": "{s["issue_date"]}",\n'
        code += f'        "maturity_date": "{s["maturity_date"]}",\n'
        code += f'        "credit_rating": "{s["credit_rating"]}",\n'
        code += f'        "credit_rating_agency": "{s["credit_rating_agency"]}",\n'
        code += f'        "asset_cover_ratio": {float(s.get("asset_cover_ratio", 1.25))},\n'
        code += f'        "is_listed": {s.get("is_listed", True)},\n'
        code += f'        "exchange": "{s.get("exchange", "BSE")}",\n'
        code += f'        "is_sdi": {s.get("is_sdi", False)},\n'
        orig = f'"{s["originator"]}"' if s.get("originator") else 'None'
        code += f'        "originator": {orig},\n'
        code += f'        "fldg_pct": {float(s.get("fldg_pct", 0.0))},\n'
